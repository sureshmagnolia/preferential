const LOCAL_STORAGE_KEY = 'preferential_nominal_roll';

export class NominalRollService {
  constructor() {
    this.roll = this.load();
  }

  load() {
    try {
      const stored = localStorage.getItem(LOCAL_STORAGE_KEY);
      if (stored && stored !== 'undefined' && stored !== 'null' && stored.trim() !== '') {
        const parsed = JSON.parse(stored);
        if (Array.isArray(parsed) && parsed.length > 0) {
          const hasOldMock = parsed.some(p => (p.rollNo && p.rollNo.startsWith('24-')) || (p.id && p.id.startsWith('VOT-')));
          if (!hasOldMock) {
            return parsed;
          }
        }
      }
    } catch (e) {
      console.warn("Could not load stored nominal roll, using default", e);
    }
    const initial = [...INITIAL_NOMINAL_ROLL];
    this.save(initial);
    return initial;
  }

  save() {
    try {
      localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(this.roll));
    } catch (e) {
      console.error("Failed to save nominal roll to localStorage", e);
    }
  }

  getAll() {
    return [...this.roll];
  }

  getDepartments() {
    const depts = new Set(this.roll.map(v => v.dept));
    return Array.from(depts).sort();
  }

  filter(query = '', department = '') {
    const cleanQ = query.trim().toLowerCase();
    return this.roll.filter(voter => {
      const matchQ = !cleanQ || 
        voter.name.toLowerCase().includes(cleanQ) || 
        voter.rollNo.toLowerCase().includes(cleanQ) ||
        voter.id.toLowerCase().includes(cleanQ);
      const matchDept = !department || voter.dept === department;
      return matchQ && matchDept;
    });
  }

  toggleVoterStatus(voterId) {
    const voter = this.roll.find(v => v.id === voterId);
    if (voter) {
      voter.status = voter.status === 'Eligible' ? 'Ballot Issued' : 'Eligible';
      this.save();
      return voter;
    }
    return null;
  }

  importCSV(csvText) {
    const lines = csvText.trim().split(/\r?\n/);
    if (lines.length < 2) throw new Error("CSV must have at least a header and one data row.");

    const header = lines[0].split(',').map(h => h.trim().toLowerCase());
    const nameIdx = header.findIndex(h => h.includes('name'));
    const deptIdx = header.findIndex(h => h.includes('dept') || h.includes('department'));
    const rollIdx = header.findIndex(h => h.includes('roll') || h.includes('sl') || h.includes('id'));
    const desigIdx = header.findIndex(h => h.includes('desig') || h.includes('year') || h.includes('rank'));

    if (nameIdx === -1) throw new Error("CSV must include a 'Name' column.");

    const newRoll = [];
    for (let i = 1; i < lines.length; i++) {
      const line = lines[i].trim();
      if (!line) continue;
      const cols = line.split(',').map(c => c.trim().replace(/^["']|["']$/g, ''));
      const id = `TCH-${String(i).padStart(3, '0')}`;
      const name = cols[nameIdx] || "Unnamed";
      const dept = deptIdx !== -1 && cols[deptIdx] ? cols[deptIdx] : "General";
      const rollNo = rollIdx !== -1 && cols[rollIdx] ? cols[rollIdx] : `GCC-${String(i).padStart(3, '0')}`;
      const year = desigIdx !== -1 && cols[desigIdx] ? cols[desigIdx] : "Faculty";

      newRoll.push({ id, rollNo, name, dept, year, status: "Eligible" });
    }

    this.roll = newRoll;
    this.save();
    return this.roll.length;
  }

  resetDefault() {
    this.roll = [...INITIAL_NOMINAL_ROLL];
    this.save();
  }
}
